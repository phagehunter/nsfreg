#!/usr/bin/env python3
"""Superseded by build.py in the repository root.

This script used to merge data/*.json into assets/entities.js on its own. The
site is now generated by build.py, which writes assets/lists.js and
assets/entities.js in a different shape and renders every page from src/ in the
same pass, so running the old merge by itself would leave the search index and
the pages disagreeing with each other.

It is kept as this shim so that an older note or habit pointing at
"python3 pipeline/build_index.py" still does the right thing.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

if __name__ == "__main__":
    print(__doc__.strip(), file=sys.stderr)
    print("\nRunning build.py instead.\n", file=sys.stderr)
    sys.exit(subprocess.call([sys.executable, str(ROOT / "build.py")] + sys.argv[1:]))
